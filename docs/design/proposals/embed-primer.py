"""Embed the installed Primer token dependency closure in the offline UX sheet.

Run from the repository root: python3 docs/design/proposals/embed-primer.py
Requires @primer/primitives 11.10.0 from the stack spike (#269).
Generated declarations retain upstream names and values; never edit them by hand.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PACKAGE = ROOT / "packages/frontend/node_modules/@primer/primitives"
TARGET = Path(__file__).with_name("ux.html")
VERSION = "11.10.0"


def declarations(path):
    css = re.sub(r"/\*.*?\*/", "", path.read_text(), flags=re.S)
    return dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", css))


def references(css):
    return set(re.findall(r"var\((--[\w-]+)", css))


def main():
    actual = json.loads((PACKAGE / "package.json").read_text())["version"]
    if actual != VERSION:
        raise ValueError(f"Expected Primer {VERSION}, got {actual}; review before updating")
    html = TARGET.read_text()
    html = re.sub(r'<style id="primer-tokens">.*?</style>\s*', "", html, flags=re.S)
    css_root = PACKAGE / "dist/css"
    base = {}
    for directory in ["base", "functional/size", "functional/spacing", "functional/typography"]:
        for path in sorted((css_root / directory).rglob("*.css")):
            base.update(declarations(path))
    themes = {
        mode: declarations(css_root / f"functional/themes/{mode}.css")
        for mode in ["light", "dark"]
    }
    own = set(re.findall(r"(--[\w-]+)\s*:", html))
    needed = references(html) - own
    pending = list(needed)
    while pending:
        name = pending.pop()
        values = [mapping[name] for mapping in [base, *themes.values()] if name in mapping]
        if not values:
            raise ValueError(f"Unknown Primer token: {name}")
        for value in values:
            for dependency in references(value) - needed - own:
                needed.add(dependency)
                pending.append(dependency)
    blocks = []
    for selector, mapping in [
        (":root", base),
        ('[data-color-mode="light"][data-light-theme="light"]', themes["light"]),
        ('[data-color-mode="dark"][data-dark-theme="dark"]', themes["dark"]),
    ]:
        lines = [f"  {name}: {mapping[name]};" for name in sorted(needed & mapping.keys())]
        blocks.append(selector + " {\n" + "\n".join(lines) + "\n}")
    license_text = (PACKAGE / "LICENSE").read_text()
    generated = (
        '<style id="primer-tokens">\n'
        f"/* Generated by embed-primer.py from @primer/primitives {VERSION}.\n"
        "   Dependency closure of upstream dist/css declarations; values are unmodified.\n"
        + license_text + "\n*/\n" + "\n".join(blocks) + "\n</style>\n"
    )
    TARGET.write_text(html.replace('<style id="proposal-styles">', generated + '<style id="proposal-styles">'))
    print(f"Embedded {len(needed)} upstream tokens ({VERSION})")


if __name__ == "__main__":
    main()
